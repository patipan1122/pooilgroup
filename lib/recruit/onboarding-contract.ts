const PLACEHOLDER_PATTERN = /\{\{([^}]*)\}\}/g;

/**
 * ค่าที่กรอกมาถูก "ยุบช่องว่าง" ให้เหลือเว้นวรรคเดียวเสมอ เพื่อให้คนเดียวกัน
 * กรอกข้อมูลชุดเดิมได้ hash เดิมเสมอ (เช่น ที่อยู่ที่ขึ้นบรรทัดใหม่จากมือถือ
 * กับที่พิมพ์ติดกันบนคอม ต้องได้สัญญาหน้าตาเดียวกัน)
 */
function cleanValue(raw: string): string {
  const text = raw.replace(/\s+/g, " ").trim();
  return text === "" ? BLANK : text;
}

function placeholderValues(vars: OnboardingContractVars): ReadonlyMap<string, string> {
  return new Map<string, string>([
    ["ชื่อบริษัท", cleanValue(vars.companyName)],
    ["ชื่อ-นามสกุล", cleanValue(vars.fullNameTh)],
    ["เลขบัตรประชาชน", cleanValue(vars.nationalId)],
    ["ที่อยู่ตามทะเบียนบ้าน", cleanValue(vars.registeredAddress)],
    ["ตำแหน่ง", cleanValue(vars.position)],
    ["สาขา", cleanValue(vars.branch)],
    ["วันเริ่มงาน", cleanValue(vars.startDate)],
    ["วันเวลาที่กดยินยอม", cleanValue(vars.signedAtText)],
  ]);
}

/**
 * แทนค่าแบบรอบเดียว (ค่าที่แทนลงไปจะไม่ถูกสแกนซ้ำ) → ผู้สมัครพิมพ์
 * "{{ตำแหน่ง}}" ลงในช่องที่อยู่ก็แทรกอะไรเข้าตัวสัญญาไม่ได้
 *
 * เจอ placeholder ที่ไม่รู้จัก = โค้ดพิมพ์ชื่อตัวแปรผิด → โยน error ทิ้ง
 * (fail-closed) ดีกว่าปล่อยเอกสารกฎหมายที่มี "{{...}}" ค้างให้พนักงานเซ็น
 */
function substitute(template: string, values: ReadonlyMap<string, string>): string {
  return template.replace(PLACEHOLDER_PATTERN, (_match, rawKey: string) => {
    const key = rawKey.trim();
    const value = values.get(key);
    if (value === undefined) {
      throw new Error(
        `[onboarding-contract] unknown placeholder {{${key}}} — เพิ่มใน placeholderValues() ก่อน`,
      );
    }
    return value;
  });
}

/**
 * ตัวสัญญาแบบมีโครงสร้าง (หัวข้อ + ย่อหน้า) สำหรับให้ UI render เป็น element จริง
 * หัวเรื่องเอกสารอยู่แยกที่ ONBOARDING_CONTRACT_TITLE (ไม่รวมอยู่ใน array นี้)
 */
export function getOnboardingContractSections(vars: OnboardingContractVars): ContractSection[] {
  const values = placeholderValues(vars);
  return CONTRACT_TEMPLATE.map((section) => ({
    id: section.id,
    heading: section.heading,
    paragraphs: section.paragraphs.map((p) => substitute(p, values)),
  }));
}

