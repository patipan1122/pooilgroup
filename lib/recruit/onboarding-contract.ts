/** นโยบายความเป็นส่วนตัวแบบ plain text (ย่อหน้าคั่นด้วยบรรทัดว่าง) */
export function renderPrivacyPolicy(companyName: string): string {
  return normalizeContractText(
    substitute(
      PRIVACY_POLICY_TEXT,
      new Map<string, string>([["ชื่อบริษัท", cleanValue(companyName)]]),
    ),
  );
}

/** เวอร์ชันแยกย่อหน้า — ให้ UI render เป็น <p> จริง ไม่ต้อง split เอง */
export function getPrivacyPolicyParagraphs(companyName: string): string[] {
  return renderPrivacyPolicy(companyName).split("\n\n");
}
