// Render + hash
// ─────────────────────────────────────────────────────────────────────────────

/**
 * รูปแบบมาตรฐานของข้อความสัญญา — ต้องเรียกทั้งตอน render และตอน hash เพื่อให้
 * ข้อความชุดเดียวกันได้ hash เดียวกันเสมอ ไม่ว่าจะเดินทางผ่าน textarea
 * (ที่แอบเปลี่ยน \n เป็น \r\n) หรือผ่านคีย์บอร์ดมือถือ (ที่ประกอบสระ/วรรณยุกต์
 * ไทยคนละแบบ → แก้ด้วย NFC)
 */
function normalizeContractText(text: string): string {
  return text
    .replace(/\r\n?/g, "\n")
    .split("\n")
    .map((line) => line.trim())
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim()
    .normalize("NFC");
}

/**
 * ตัวสัญญาเป็น plain text ทั้งฉบับ (หัวเรื่อง + 10 ข้อ + ท้ายเอกสาร)
 * ใช้สำหรับคำนวณ hash, แนบอีเมล, และทำสำเนาเก็บ
 */
export function renderOnboardingContract(vars: OnboardingContractVars): string {
  const blocks: string[] = [ONBOARDING_CONTRACT_TITLE];
  for (const section of getOnboardingContractSections(vars)) {
    const lines = section.heading === "" ? section.paragraphs : [section.heading, ...section.paragraphs];
    blocks.push(lines.join("\n"));
  }
  return normalizeContractText(blocks.join("\n\n"));
}

/** SHA-256 (hex) ของข้อความสัญญา — normalize ก่อนเสมอ ผลลัพธ์จึง deterministic */
export function hashContractText(text: string): string {
  return createHash("sha256").update(normalizeContractText(text), "utf8").digest("hex");
}

/**
 * ⭐ ตัวที่ควรเรียกตอนบันทึกการเซ็น (และตอน audit ย้อนหลัง)
 *
 * จงใจ hash ฉบับที่ signedAtText = "" เพราะ "วันเวลาที่กดยินยอม" คือค่าที่
 * เกิด ณ วินาทีที่กดปุ่ม — ถ้าเอาไปรวมใน hash จะได้ hash คนละตัวกับตอนที่
 * พนักงานนั่งอ่าน (ตอนอ่านยังไม่มีเวลากดยินยอม) → พิสูจน์ไม่ได้ว่า
 * "ข้อความที่เขาอ่าน = ข้อความที่เราเก็บ" ซึ่งคือทั้งหมดที่ hash นี้มีไว้ทำ
 * ส่วนเวลาที่เซ็นเก็บแยกเป็นคอลัมน์ signedAt อยู่แล้ว (แก้ไม่ได้เหมือนกัน)
 *
 * ผลข้างเคียงที่ต้องการ: ค่าใน vars ทุกตัว (ชื่อ เลขบัตร ที่อยู่ ตำแหน่ง สาขา
 * วันเริ่มงาน ชื่อบริษัท) ยังอยู่ใน hash ครบ → ใครแก้ทีหลัง hash ไม่ตรงทันที
 */
export function hashOnboardingContract(vars: OnboardingContractVars): string {
  return hashContractText(renderOnboardingContract({ ...vars, signedAtText: "" }));
}

