function norm(s: string | null | undefined): string {
  return (s ?? "").toLowerCase();
}

function high(name: string): CategorySuggestion {
  const gl = GL_BY_NAME.get(name);
  if (gl) return { categoryName: name, glCode: gl, confidence: "high" };
  return fallback();
}

function fallback(): CategorySuggestion {
  return { categoryName: FALLBACK_NAME, glCode: GL_BY_NAME.get(FALLBACK_NAME) ?? "5210450", confidence: "low" };
}

// วิเคราะห์หมวดที่ควรลง ถ้าบันทึกใบนี้เป็น AP
export function suggestExpenseCategory(
  vendor: string | null | undefined,
  note: string | null | undefined,
): CategorySuggestion {
  const noteHay = norm(note);
  const vendorHay = norm(vendor);

  // รอบ 1: ดูจาก "รายละเอียดในใบ" ก่อน — บอกว่าซื้ออะไรจริง (สำคัญกว่าชื่อร้าน)
  if (noteHay) {
    for (const rule of RULES) {
      if (rule.kw.some((k) => noteHay.includes(k))) return high(rule.name);
    }
  }
  // รอบ 2: เดาจากชื่อร้าน
  if (vendorHay) {
    for (const rule of RULES) {
      if (rule.kw.some((k) => vendorHay.includes(k))) return high(rule.name);
    }
  }
  return fallback();
}
