// GET /api/clawfleet/import/collections/template
// คืนไฟล์ .xlsx แม่แบบสำหรับนำเข้าข้อมูลเก็บเงิน/เติมตุ๊กตา ClawFleet.
// เฉพาะแอดมิน ClawFleet (assertCfAdmin). ไฟล์มี 3 แท็บ:
//   แท็บ 1 "กรอกข้อมูล"     — หัวตาราง + 2 แถวตัวอย่าง (ระบบข้ามให้) + 1 แถว/ตู้ (เติมสาขา+รหัสให้แล้ว)
//   แท็บ 2 "วิธีใช้"         — อธิบายทุกคอลัมน์ภาษาไทย
//   แท็บ 3 "รายชื่อสาขา+ตู้"  — รายการตู้จริงทั้งหมด (สาขา · รหัสตู้ · ชื่อเล่น) ไว้ copy

import { type NextRequest, NextResponse } from "next/server";
import * as XLSX from "xlsx";
import { assertCfAdmin } from "@/lib/clawfleet/role-guard";
import { prisma } from "@/lib/prisma";
import { IMPORT_HEADER_LABELS } from "@/app/(admin)/clawfleet/os/import/types";

export const dynamic = "force-dynamic";

export async function GET(_req: NextRequest) {
  const session = await assertCfAdmin();
  const orgId = session.user.org_id;

  // ตู้คีบ (CLAW) ที่ยัง active · เรียงตามสาขา แล้วรหัสตู้.
  const machines = await prisma.cfMachine.findMany({
    where: { orgId, kind: "CLAW", isActive: true },
    select: {
      code: true,
      nickname: true,
      isFirstBaselineLocked: true,
      branch: { select: { name: true, code: true } },
    },
    orderBy: [{ branch: { name: "asc" } }, { code: "asc" }],
  });

  const now = new Date();
  const dateStr = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, "0")}-${String(now.getDate()).padStart(2, "0")}`;
  const exBranch = machines[0]?.branch.name ?? "สาขาตัวอย่าง";
  const exCode = machines[0]?.code ?? "CW-001";

  const wb = XLSX.utils.book_new();

  // ── แท็บ 1: กรอกข้อมูล ────────────────────────────────────────────────────
  // แถวแรก = หัวตาราง (ห้ามแก้ชื่อ). ตามด้วย 2 แถวตัวอย่าง (สาขาขึ้นต้น "ตัวอย่าง"
  // → previewCollectionsFile ข้ามให้อัตโนมัติ ไม่ต้องลบ) แล้ว 1 แถว/ตู้ (เติมสาขา+รหัสให้)
  // คอลัมน์: สาขา รหัสตู้ วันที่ มิเตอร์เงินบน มิเตอร์เงินล่าง เงินที่เก็บ ตุ๊กตาก่อนเติม จำนวนที่เติม ตุ๊กตาหลังเติม มิเตอร์ตุ๊กตาบน มิเตอร์ตุ๊กตาล่าง
  const dataSheet: (string | number)[][] = [
    [...IMPORT_HEADER_LABELS],
    [
      `ตัวอย่าง ▸ ${exBranch} (ระบบข้ามแถวนี้ให้)`,
      exCode,
      dateStr,
      120500, // มิเตอร์เงินบน
      120500, // มิเตอร์เงินล่าง
      3400, // เงินที่เก็บ (บาท)
      45, // ตุ๊กตาก่อนเติม
      20, // จำนวนที่เติม
      65, // ตุ๊กตาหลังเติม
      880, // มิเตอร์ตุ๊กตาบน
      880, // มิเตอร์ตุ๊กตาล่าง
    ],
    [
      "ตัวอย่าง ▸ ตู้หน้าปัดล่างเสีย (กรอกแค่ด้านบนได้)",
      exCode,
      dateStr,
      98000, // มิเตอร์เงินบน
      "", // มิเตอร์เงินล่าง (เว้นได้ ถ้าหน้าปัดเสีย)
      2100,
      30,
      0, // ไม่เติมวันนี้
      30,
      "",
      "",
    ],
    // 1 แถว/ตู้ · เติมสาขา+รหัสให้แล้ว กรอกแค่ตัวเลข (แถวที่ไม่กรอกเลข ระบบข้ามให้)
    ...machines.map((m) => [m.branch.name, m.code, "", "", "", "", "", "", "", "", ""]),
  ];
  const ws1 = XLSX.utils.aoa_to_sheet(dataSheet);
  ws1["!cols"] = [
    { wch: 30 }, // สาขา
    { wch: 12 }, // รหัสตู้
    { wch: 13 }, // วันที่
    { wch: 13 }, // มิเตอร์เงินบน
    { wch: 13 }, // มิเตอร์เงินล่าง
    { wch: 13 }, // เงินที่เก็บ
    { wch: 12 }, // ตุ๊กตาก่อนเติม
    { wch: 11 }, // จำนวนที่เติม
    { wch: 12 }, // ตุ๊กตาหลังเติม
    { wch: 13 }, // มิเตอร์ตุ๊กตาบน
    { wch: 13 }, // มิเตอร์ตุ๊กตาล่าง
  ];
  XLSX.utils.book_append_sheet(wb, ws1, "กรอกข้อมูล");

  // ── แท็บ 2: วิธีใช้ ────────────────────────────────────────────────────────
  const guide: string[][] = [
    ["คอลัมน์", "อธิบาย", "ตัวอย่าง", "บังคับ?"],
    ["สาขา", "ชื่อสาขาจริง (พิมพ์ได้เลย) หรือรหัสสาขา — ในไฟล์เติมให้แล้วทุกตู้", exBranch, "✅ บังคับ"],
    ["รหัสตู้", "รหัสตู้ (ดูได้ที่แท็บ 'รายชื่อสาขา+ตู้') — ในไฟล์เติมให้แล้ว", exCode, "✅ บังคับ"],
    ["วันที่", `วันที่เก็บเงิน รูปแบบ ${"YYYY-MM-DD"} (ใส่เวลาต่อท้ายก็ได้ HH:mm)`, dateStr, "✅ บังคับ"],
    ["มิเตอร์เงินบน", "เลขมิเตอร์เงินหน้าปัดบน (ที่เห็นวันนี้)", "120500", "◑ อย่างน้อย 1 ด้าน"],
    ["มิเตอร์เงินล่าง", "เลขมิเตอร์เงินหน้าปัดล่าง — หน้าปัดล่างเสีย เว้นว่างได้ (ระบบใช้ด้านบน)", "120500", "◑ อย่างน้อย 1 ด้าน"],
    ["เงินที่เก็บ(บาท)", "เงินสดที่นับได้จริงในตู้ (บาท · จำนวนเต็มบวก)", "3400", "✅ บังคับ"],
    ["ตุ๊กตาก่อนเติม", "จำนวนตุ๊กตาในตู้ก่อนเติม (นับจริง)", "45", "⬜ ใส่หรือเว้นได้"],
    ["จำนวนที่เติม", "จำนวนตุ๊กตาที่เติมเข้าตู้วันนี้ (ไม่เติม = 0 หรือเว้น)", "20", "⬜ ใส่หรือเว้นได้"],
    ["ตุ๊กตาหลังเติม", "จำนวนตุ๊กตาในตู้หลังเติม (นับจริง)", "65", "⬜ ใส่หรือเว้นได้"],
    ["มิเตอร์ตุ๊กตาบน", "เลขมิเตอร์ตุ๊กตาหน้าปัดบน (ถ้าตู้มี)", "880", "⬜ ใส่หรือเว้นได้"],
    ["มิเตอร์ตุ๊กตาล่าง", "เลขมิเตอร์ตุ๊กตาหน้าปัดล่าง (ถ้าตู้มี)", "880", "⬜ ใส่หรือเว้นได้"],
    [],
    ["⚠ หมายเหตุ", "", "", ""],
    ["- ห้ามแก้ชื่อคอลัมน์ในแถวแรกของแท็บ 'กรอกข้อมูล'", "", "", ""],
    ["- 2 แถวแรกที่ขึ้นต้น \"ตัวอย่าง\" = ตัวอย่างให้ดู ระบบข้ามให้ (ไม่ต้องลบ)", "", "", ""],
    ["- ไฟล์เติมสาขา+รหัสตู้ให้แล้วทุกตู้ — กรอกแค่ตัวเลขข้างตู้ที่เก็บ", "", "", ""],
    ["- ตู้ที่ไม่ได้กรอกวันที่+เงิน ระบบจะข้ามให้ (ไม่ต้องลบแถว)", "", "", ""],
    ["- กรอกได้หลายตู้ + หลายวัน ในไฟล์เดียว (1 แถว = 1 ตู้ 1 วัน · วันใหม่ก็ก๊อปแถวเพิ่ม)", "", "", ""],
    ["- ตู้ที่ยังไม่เคยมีข้อมูลในระบบ แถวแรกสุด (วันเก่าสุด) = 'ตั้งค่าครั้งแรก' อัตโนมัติ", "", "", ""],
    ["- ไม่ต้องระบุ SKU/ชื่อตุ๊กตา — กรอกแค่จำนวนพอ", "", "", ""],
    ["- รองรับไฟล์ .xlsx และ .csv · อัปแล้วมีหน้าพรีวิวให้ตรวจก่อนบันทึกจริง", "", "", ""],
  ];
  const ws2 = XLSX.utils.aoa_to_sheet(guide);
  ws2["!cols"] = [{ wch: 18 }, { wch: 60 }, { wch: 14 }, { wch: 18 }];
  XLSX.utils.book_append_sheet(wb, ws2, "วิธีใช้");

  // ── แท็บ 3: รายชื่อสาขา+ตู้ ─────────────────────────────────────────────────
  const listSheet: string[][] = [
    ["สาขา", "รหัสตู้ (พิมพ์ในช่อง รหัสตู้)", "ชื่อเล่นตู้", "สถานะในระบบ"],
    ...machines.map((m) => [
      m.branch.name,
      m.code,
      m.nickname ?? "",
      m.isFirstBaselineLocked ? "มีข้อมูลแล้ว" : "ยังไม่ตั้งค่า (แถวแรก=ตั้งค่าครั้งแรก)",
    ]),
  ];
  const ws3 = XLSX.utils.aoa_to_sheet(listSheet);
  ws3["!cols"] = [{ wch: 30 }, { wch: 26 }, { wch: 22 }, { wch: 34 }];
  XLSX.utils.book_append_sheet(wb, ws3, "รายชื่อสาขา+ตู้");

  const bytes = XLSX.write(wb, { type: "array", bookType: "xlsx" }) as number[];
  const blob = new Blob([new Uint8Array(bytes)], {
    type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
  });

  return new NextResponse(blob, {
    headers: {
      "Content-Disposition": 'attachment; filename="clawfleet-collections-template.xlsx"',
      "Cache-Control": "no-store",
    },
  });
}
