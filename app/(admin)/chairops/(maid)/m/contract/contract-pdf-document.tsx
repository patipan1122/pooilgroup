const SITE_URL = process.env.NEXT_PUBLIC_APP_URL ?? "https://pooilgroup.vercel.app";

let fontsRegistered = false;
/** Self-hosted TTF served from our own /public (not @fontsource — that ships
 *  woff/woff2 only, which silently produced a blank page in testing; fontkit
 *  needs real ttf/otf). Fetched over plain HTTPS from our own domain, so it
 *  works identically in local dev and on Vercel with zero serverless
 *  filesystem-bundling risk (no fs.readFileSync of a `public/` path, whose
 *  presence in the deployed function bundle is not guaranteed). */
function ensureFonts() {
  if (fontsRegistered) return;
  Font.register({
    family: "IBMPlexSansThai",
    fonts: [
      { src: `${SITE_URL}/fonts/ibm-plex-sans-thai-regular.ttf`, fontWeight: 400 },
      { src: `${SITE_URL}/fonts/ibm-plex-sans-thai-bold.ttf`, fontWeight: 700 },
    ],
  });
  fontsRegistered = true;
}

