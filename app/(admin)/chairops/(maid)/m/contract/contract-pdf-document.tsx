// Real, downloadable PDF version of the signed maid contract (CEO 2026-09-23).
//
// SERVER-ONLY — never import this from a "use client" component. Two reasons:
//   1. @react-pdf/renderer's browser build fetches remote images (ID card /
//      selfie / signature, all on R2's public `*.r2.dev` domain) via fetch(),
//      which the site's CSP connect-src blocks (only allows
//      *.r2.cloudflarestorage.com, not *.r2.dev — see lib/supabase/proxy.ts).
//      Server-side Node fetch has no CSP at all, so rendering here sidesteps
//      the whole problem instead of loosening a site-wide security header.
//   2. Keeps react-pdf's fairly heavy dependency tree out of the client bundle
//      entirely — this document is generated by the API route in
//      app/api/chairops/contract/pdf/route.ts and streamed down as a file.
//
// This is a PARALLEL implementation of contract-document.tsx (the on-screen
// HTML preview) — @react-pdf/renderer uses its own View/Text/Image primitives,
// not DOM/CSS, so the JSX can't be shared. Keep the Thai wording of both IN
// SYNC BY HAND whenever either changes.

